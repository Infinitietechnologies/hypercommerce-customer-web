#!/usr/bin/env node
import { execFileSync } from "node:child_process";

const git = (args) => execFileSync("git", args, {
  encoding: "utf8", maxBuffer: 32 * 1024 * 1024, windowsHide: true,
});

// Read the index: changing a working file after staging must not hide its content.
const files = git(["diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z"])
  .split("\0").filter(Boolean);
const violations = [];
const packagePath = /^(?:plugins|src\/plugins|public\/plugins)(?:\/|$)/i;
const sourceFile = /\.(?:[cm]?[jt]sx?|css|scss)$/i;
const infrastructure = /^(?:tests\/|scripts\/plugin-system\/|\.claude\/)/;
const appendMarker = /(?:\{\/\*|\/\*)\s*hyperlocal-plugin:[^\r\n]*:(?:start|end)\s*\*\/\}?/;
const routeMarker = /^\s*\/\/ Generated by the plugin installer\./m;
const installedImport = /\b(?:from\s*|import\s*\()\s*["'](?:@\/|(?:\.\.?\/)+)(?:src\/)?plugins\//;

for (const file of files) {
  if (packagePath.test(file) && file !== "src/plugins/registry.json") {
    violations.push([file, "plugin package or installed output"]);
    continue;
  }
  if (file.toLowerCase() === "plugin-config.local.json") {
    violations.push([file, "local plugin configuration"]);
    continue;
  }
  if (file === "src/plugins/registry.json") {
    let empty = false;
    try {
      const value = JSON.parse(git(["show", `:${file}`]));
      empty = Array.isArray(value) && value.length === 0;
    } catch { /* A malformed registry must not bypass the guard. */ }
    if (!empty) violations.push([file, "installed plugin registry (only the empty baseline is allowed)"]);
    continue;
  }
  if (/^public\/locales\/[^/]+\.json$/i.test(file)) {
    let labels;
    try { labels = JSON.parse(git(["show", `:${file}`])); }
    catch { throw new Error(`Cannot check staged locale JSON: ${file}`); }
    if (labels && typeof labels === "object" && Object.keys(labels).some((key) => key.startsWith("plugin:"))) {
      violations.push([file, "installed plugin translations"]);
    }
    continue;
  }
  if (!sourceFile.test(file) || infrastructure.test(file)) continue;
  const content = git(["show", `:${file}`]);
  if (appendMarker.test(content) || routeMarker.test(content) || installedImport.test(content)) {
    violations.push([file, "installed plugin route, import or managed source block"]);
  }
}

if (violations.length) {
  console.error("Plugin commit blocked. Keep plugin packages, installed output, and local configuration out of the storefront repository.");
  for (const [file, reason] of violations) console.error(`  ${file}: ${reason}`);
  console.error("Unstage these paths. Commit plugin inputs in their own repository and keep installed contributions local.");
  console.error("No files or staged changes were modified by this check.");
  process.exitCode = 1;
} else {
  console.log("Plugin commit check passed.");
}

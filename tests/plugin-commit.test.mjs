test("the real pre-commit hook blocks a Git commit before it creates history", async (t) => {
  const f = await fixture(t);
  const hook = await fs.readFile(path.join(repository, ".githooks/pre-commit"));
  await f.stage(".githooks/pre-commit", hook);
  await fs.chmod(path.join(f.root, ".githooks/pre-commit"), 0o755);
  await f.stage("scripts/check-plugin-commit.mjs", await fs.readFile(guard));
  await f.stage("plugins/flash-sales/plugin.json", '{"id":"flash-sales"}');
  f.git("config", "core.hooksPath", ".githooks");
  const result = spawnSync("git", ["-c", "user.name=Plugin Test", "-c", "user.email=test@example.invalid", "-c", "commit.gpgsign=false", "commit", "-m", "must be blocked"], { cwd: f.root, encoding: "utf8", windowsHide: true });
  assert.equal(result.status, 1);
  assert.match(result.stderr, /Plugin commit blocked/);
  assert.equal(spawnSync("git", ["rev-parse", "--verify", "HEAD"], { cwd: f.root, windowsHide: true }).status, 128);
});

test("hook setup enables the tracked hook and preserves an existing custom hook path", async (t) => {
  const f = await fixture(t);
  await f.write("scripts/setup-git-hooks.mjs", await fs.readFile(path.join(repository, "scripts/setup-git-hooks.mjs")));
  await f.write(".githooks/pre-commit", "#!/bin/sh\nexit 0\n");
  const setup = () => spawnSync(process.execPath, ["scripts/setup-git-hooks.mjs"], { cwd: f.root, encoding: "utf8", windowsHide: true });
  assert.equal(setup().status, 0);
  assert.equal(f.git("config", "--get", "core.hooksPath").trim(), ".githooks");
  f.git("config", "core.hooksPath", "custom-hooks");
  const result = setup();
  assert.equal(result.status, 0);
  assert.match(result.stderr, /npm run check:plugin-commit/);
  assert.equal(f.git("config", "--get", "core.hooksPath").trim(), "custom-hooks");
});

test("hook setup skips installer candidates without Git metadata", async (t) => {
  const f = await fixture(t);
  const candidate = path.join(f.root, "candidate");
  await f.write("candidate/scripts/setup-git-hooks.mjs", await fs.readFile(path.join(repository, "scripts/setup-git-hooks.mjs")));
  const result = spawnSync(process.execPath, ["scripts/setup-git-hooks.mjs"], { cwd: candidate, encoding: "utf8", windowsHide: true });
  assert.equal(result.status, 0);
  assert.match(result.stdout, /skipped outside a checkout/);
  assert.throws(() => f.git("config", "--get", "core.hooksPath"));
});

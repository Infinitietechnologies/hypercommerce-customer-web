import test from "node:test";
import assert from "node:assert/strict";
import * as fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { execFileSync, spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const repository = fileURLToPath(new URL("../", import.meta.url));
const guard = path.join(repository, "scripts/check-plugin-commit.mjs");

async function fixture(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "hyperlocal-plugin-commit-"));
  t.after(async () => {
    const target = path.resolve(root);
    assert.equal(path.dirname(target), path.resolve(os.tmpdir()));
    assert.ok(path.basename(target).startsWith("hyperlocal-plugin-commit-"));
    await fs.rm(target, { recursive: true, force: true, maxRetries: 4, retryDelay: 50 });
  });
  const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8", windowsHide: true });
  git("init", "--quiet");
  const write = async (name, content) => {
    const target = path.join(root, name);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, content);
  };
  const stage = async (name, content) => { await write(name, content); git("add", "-f", "--", name); };
  const check = () => spawnSync(process.execPath, [guard], { cwd: root, encoding: "utf8", windowsHide: true });
  return { root, git, write, stage, check };
}

for (const name of ["plugins/flash-sales/plugin.json", "src/plugins/flash-sales/src/Page.tsx", "public/plugins/flash-sales/image.svg"]) {
  test(`rejects force-staged plugin files: ${name}`, async (t) => {
    const f = await fixture(t);
    await f.stage(name, "plugin content");
    const before = f.git("diff", "--cached");
    const result = f.check();
    assert.equal(result.status, 1);
    assert.match(result.stderr, /Plugin commit blocked/);
    assert.equal(f.git("diff", "--cached"), before);
  });
}

test("rejects force-staged local plugin configuration without displaying its values", async (t) => {
  const f = await fixture(t);
  await f.stage("plugin-config.local.json", '{"sample":{"installer":{"key":"private-test-value"}}}');
  const result = f.check();
  assert.equal(result.status, 1);
  assert.match(result.stderr, /local plugin configuration/);
  assert.doesNotMatch(result.stderr, /private-test-value/);
});

for (const content of [
  "/* hyperlocal-plugin:flash-sales:homepage:import:start */\nimport Feature from './feature';\n/* hyperlocal-plugin:flash-sales:homepage:import:end */",
  "export default () => <>{/* hyperlocal-plugin:flash-sales:homepage:section:start */}<Feature />{/* hyperlocal-plugin:flash-sales:homepage:section:end */}</>;",
  "// Generated by the plugin installer.\nexport { default } from '../../plugins/flash-sales/src/Page';",
  "import Feature from '@/plugins/flash-sales/src/Page';",
]) {
  test(`rejects staged installed source: ${content.slice(0, 52)}`, async (t) => {
    const f = await fixture(t);
    await f.stage("src/pages/with space.tsx", content);
    // The working copy is clean, but the staged plugin still must be rejected.
    await f.write("src/pages/with space.tsx", "export default () => null;");
    assert.equal(f.check().status, 1);
  });
}

test("rejects plugin locale namespaces and nonempty registries", async (t) => {
  const f = await fixture(t);
  await f.stage("public/locales/en.json", JSON.stringify({ existing: "Keep", "plugin:flash-sales": { title: "Sale" } }));
  await f.stage("src/plugins/registry.json", '[{"id":"flash-sales"}]');
  const result = f.check();
  assert.equal(result.status, 1);
  assert.match(result.stderr, /installed plugin translations/);
  assert.match(result.stderr, /installed plugin registry/);
});

